const assert=require('node:assert/strict');
const {normalizeContent,normalizeActivity,validateDetails,ageAt,contentVersion}=require('../packages/shared');
const migrated=normalizeContent({schemaVersion:5,activities:[{id:'camp-custom',kind:'camp',gradeOptions:['الثالث','الرابع','الخامس'],allowedGrades:['الثالث','الرابع']}]});
assert.equal(migrated.schemaVersion,contentVersion);
assert.deepEqual(migrated.activities[0].gradeOptions,['الثالث','الرابع']);
const revised=normalizeContent({...migrated,activities:[{...migrated.activities[0],gradeOptions:['الثالث','الخامس']}]});
assert.deepEqual(normalizeContent(revised).activities[0].gradeOptions,['الثالث','الخامس']);
const activity=normalizeActivity({...revised.activities[0],dobMin:'2008-01-01',dobMax:'2012-12-31',useAgeLimits:true,minAge:99,maxAge:99,date:'2026-07-01'});
const details={dob:'2010-01-01',age:String(ageAt('2010-01-01','2026-07-01')),grade:'الخامس'};
assert.equal(validateDetails(details,activity).grade,undefined);
assert.equal(validateDetails({...details,grade:'الرابع'},activity).grade,'اختر صف المشارك.');
assert.equal(validateDetails(details,activity).dob,undefined);
for(const dob of ['2007-12-31','2013-01-01'])assert.ok(validateDetails({...details,dob},activity).dob);
for(const dob of ['2008-01-01','2012-12-31'])assert.equal(validateDetails({...details,dob,age:String(ageAt(dob,activity.date))},activity).dob,undefined);
assert.ok(validateDetails({...details,dob:'2013-01-01'},{...activity,registrationTestMode:true}).dob);
console.log('PASS: preserve legacy dropdown, new dropdown alone controls grades, DOB endpoints inclusive, hidden age settings ignored, supplied preview DOB respects range');
const disabled=normalizeActivity({...activity,collectCity:false,collectSchool:false,collectShirtSize:false});
const errors=validateDetails(details,disabled);
for(const key of ['city','school','shirtSize'])assert.equal(errors[key],undefined);
const enabled=normalizeActivity({...disabled,collectCity:true,collectSchool:true,collectShirtSize:true});
for(const key of ['city','school','shirtSize'])assert.ok(validateDetails(details,enabled)[key]);
const event=normalizeActivity({...enabled,kind:'event'});
for(const key of ['city','school','shirtSize'])assert.ok(validateDetails(details,event)[key]);
console.log('PASS: per-activity collection switches control camp and event field requirements');
for(const registrationTestMode of [true,false])assert.equal(normalizeContent({...revised,registrationTestMode}).registrationTestMode,registrationTestMode);
console.log('PASS: test mode remains enabled or disabled through content normalization');
